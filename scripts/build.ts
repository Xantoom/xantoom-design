// `bun run build`: tokens → CSS, then one minified stylesheet, one file per theme and the optional script, in dist/.
import { readdirSync } from 'node:fs';
import { basename, join } from 'node:path';
import { gzipSync, brotliCompressSync } from 'node:zlib';
import { bundle } from 'lightningcss';
import { declaration, flatten, knob } from './tokens.ts';

const ROOT = join(import.meta.dir, '..');
const at = (...parts: string[]): string => join(ROOT, ...parts);
const HEADER = '/* Generated by scripts/build.ts from tokens/: do not edit. */\n';

/**
 * The oldest browsers the output must keep working in: none of these needs a transform for the features the source
 * uses (nesting, light-dark(), @layer), so lightningcss passes them through.
 */
const TARGETS = { chrome: 123 << 16, firefox: 128 << 16, safari: (17 << 16) | (5 << 8), ios_saf: (17 << 16) | (5 << 8) };

/** Bundling drops the order statement of src/index.css: restate it, so a consumer's own layers can be placed around it. */
const ORDER = '@layer x.reset,x.tokens,x.theme,x.base,x.layout,x.components,x.motion,x.utilities;';

/** Derived values each theme restates, so a `data-x-theme` subtree recomputes them from its own stops. */
const DERIVED = [
	'--x-fill: linear-gradient(115deg, var(--x-fill-1), var(--x-fill-2) 48%, var(--x-fill-3));',
	'--x-brand: linear-gradient(115deg, var(--x-brand-1), var(--x-brand-2) 48%, var(--x-brand-3));',
];

const read = async (path: string): Promise<Record<string, unknown>> => (await Bun.file(path).json()) as Record<string, unknown>;

const rule = (selector: string, lines: readonly string[]): string => `\t${selector} {\n${lines.map((l) => `\t\t${l}\n`).join('')}\t}\n`;

export async function themeCss(file: string, selector: string): Promise<string> {
	const lines = flatten(await read(file)).map((t) => declaration(knob(t)));
	return rule(selector, [...lines, ...DERIVED]);
}

export const THEMES = readdirSync(at('tokens/themes'))
	.filter((f) => f.endsWith('.tokens.json'))
	.map((f) => basename(f, '.tokens.json'))
	.sort();

async function build(): Promise<void> {
	// 1. The signature tokens, plus the default (xantoom) theme so the stylesheet works alone.
	const base = flatten(await read(at('tokens/xantoom.tokens.json'))).map(declaration);
	const tokens = `${HEADER}@layer x.tokens {\n${rule(':root', base)}}\n@layer x.theme {\n${await themeCss(at('tokens/themes/xantoom.tokens.json'), ':root')}}\n`;
	await Bun.write(at('src/tokens.css'), tokens);

	// 2. One stylesheet, and the foundation alone (no components) for apps that bring their own.
	for (const [source, target] of [['src/index.css', 'dist/xantoom.css'], ['src/foundation.css', 'dist/foundation.css']]) {
		const { code } = bundle({ filename: at(source), minify: true, targets: TARGETS, errorRecovery: false });
		await Bun.write(at(target), ORDER + code.toString());
	}

	// 3. Themes: one file per app (`:root`), and all of them keyed by `data-x-theme` (demos, previews, nested themes).
	const all: string[] = [];
	for (const name of THEMES) {
		const file = at(`tokens/themes/${name}.tokens.json`);
		await Bun.write(at(`dist/themes/${name}.css`), `@layer x.theme {\n${await themeCss(file, ':root')}}\n`);
		all.push(await themeCss(file, `[data-x-theme="${name}"]`));
	}
	await Bun.write(at('dist/themes/all.css'), `@layer x.theme {\n${all.join('')}}\n`);

	// 4. The optional behaviour layer.
	const js = await Bun.build({ entrypoints: [at('src/xantoom.js')], minify: true, format: 'esm', target: 'browser' });
	if (!js.success) throw new AggregateError(js.logs, 'script build failed');
	await Bun.write(at('dist/xantoom.js'), (await js.outputs[0]?.text()) ?? '');

	for (const file of ['dist/xantoom.css', 'dist/foundation.css', 'dist/xantoom.js', 'dist/themes/vexode.css']) {
		const bytes = await Bun.file(at(file)).bytes();
		const kb = (n: number): string => `${(n / 1024).toFixed(1)} KB`;
		console.log(`${file}: ${kb(bytes.length)}, gzip ${kb(gzipSync(bytes).length)}, brotli ${kb(brotliCompressSync(bytes).length)}`);
	}
}

if (import.meta.main) await build();
